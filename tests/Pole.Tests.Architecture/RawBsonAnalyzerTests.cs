using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Pole.Architecture;
using Pole.ArchitectureAnalyzers;
using Xunit;

namespace Pole.Tests.Architecture;

public sealed class RawBsonAnalyzerTests
{
    private static readonly MetadataReference[] References = FrameworkReferences()
        .Append(MetadataReference.CreateFromFile(typeof(ViolateArchitectureAttribute).Assembly.Location))
        .Append(BsonReference())
        .ToArray();

    [Theory]
    [InlineData("BsonDocument")]
    [InlineData("BsonArray")]
    [InlineData("BsonValue")]
    public async Task All_three_real_BSON_types_are_rejected(string type)
    {
        Assert.NotEmpty(await Analyze($"using MongoDB.Bson; public class Subject {{ public {type}? Value; }}"));
    }

    [Theory]
    [InlineData("using Raw = MongoDB.Bson.BsonDocument; public class Subject { public Raw? Value; }")]
    [InlineData("global using Raw = MongoDB.Bson.BsonDocument; public class Subject { public Raw? Value; }")]
    [InlineData("using @var = MongoDB.Bson.BsonDocument; public class Subject { public @var? Value; }")]
    [InlineData("public class Subject { public global::MongoDB.Bson.BsonArray? Value; }")]
    [InlineData("public class Subject { public object Get() => BsonLibrary.Raw.Make(); }")]
    [InlineData("public class Subject { public object Get() => BsonLibrary.Raw.Values; }")]
    [InlineData("public class Subject { public object Get() => BsonLibrary.Raw.MakeTask(); }")]
    [InlineData("public class Subject { public object? Get() => BsonLibrary.Raw.Maybe(); }")]
    public async Task Aliases_qualified_names_and_inferred_returns_cannot_hide_BSON(string source)
    {
        Assert.NotEmpty(await Analyze(source));
    }

    [Theory]
    [InlineData("null!")]
    [InlineData("1")]
    public async Task Implicit_arguments_cannot_hide_BSON(string argument)
    {
        Assert.NotEmpty(await Analyze($$"""
            public class Subject { public void Execute() => BsonLibrary.Raw.AcceptValue({{argument}}); }
            """));
    }

    [Fact]
    public async Task Inferred_method_groups_cannot_hide_BSON()
    {
        Assert.NotEmpty(await Analyze("""
            public class Subject { public object Get() { var callback = BsonLibrary.Raw.AcceptValue; return callback; } }
            """));
    }

    [Fact]
    public async Task Unused_inferred_callback_parameters_cannot_hide_BSON()
    {
        Assert.NotEmpty(await Analyze("""
            public class Subject { public void Execute() => BsonLibrary.Raw.Visit(document => { }); }
            """));
    }

    [Fact]
    public async Task Out_variables_cannot_hide_BSON()
    {
        Assert.NotEmpty(await Analyze("""
            public class Subject { public bool Execute() => BsonLibrary.Raw.TryValue(out var document); }
            """));
    }

    [Fact]
    public async Task Generated_production_code_requires_the_same_exception()
    {
        Assert.NotEmpty(await Analyze("""
            // <auto-generated/>
            public class Subject { public MongoDB.Bson.BsonDocument? Value; }
            """));
    }

    [Fact]
    public async Task Namesakes_comments_and_literals_are_not_BSON_references()
    {
        Assert.Empty(await Analyze("""
            // MongoDB.Bson.BsonDocument is a comment.
            public class BsonDocument { }
            public class Subject
            {
                public BsonDocument Get() => new();
                public string Text => "BsonArray MongoDB.Bson.BsonValue";
            }
            """));
    }

    [Fact]
    public async Task Anonymous_types_without_a_namespace_do_not_crash_the_analyzer()
    {
        Assert.Empty(await Analyze("public class Subject { public object Get() => new { Value = 1 }; }"));
    }

    [Theory]
    [InlineData("Migration", false)]
    [InlineData("TestSupport", false)]
    [InlineData("Production", true)]
    public async Task Exemptions_follow_project_role_and_test_metadata(string role, bool test)
    {
        Assert.Empty(await Analyze("public class Subject { public MongoDB.Bson.BsonDocument? Value; }", role, test));
    }

    [Fact]
    public async Task Folder_names_do_not_grant_project_exemptions()
    {
        Assert.NotEmpty(await Analyze("public class Subject { public MongoDB.Bson.BsonDocument? Value; }",
            path: "Feature.Application/Migrations/Tests/Subject.cs"));
    }

    [Theory]
    [InlineData("[ViolateArchitecture(ArchitectureRules.RawBson, \"Driver serialization boundary.\")]")]
    [InlineData("[ViolateArchitecture(\"POLE014\", \"Database-time expression.\")]")]
    public async Task Deliberate_method_exceptions_cover_signature_and_body(string attribute)
    {
        Assert.Empty(await Analyze($$"""
            using MongoDB.Bson;
            using Pole.Architecture;
            public class Subject
            {
                {{attribute}}
                public BsonDocument Get() => BsonLibrary.Raw.Make();
            }
            """));
    }

    [Fact]
    public async Task Exception_does_not_escape_to_siblings_callers_or_derived_types()
    {
        var results = await Analyze("""
            using MongoDB.Bson;
            using Pole.Architecture;
            [ViolateArchitecture("POLE014", "Driver boundary owned by this type.")]
            public class Allowed { public static BsonDocument Get() => BsonLibrary.Raw.Make(); }
            public class Subject : Allowed
            {
                [ViolateArchitecture("POLE014", "This method needs the same driver contract.")]
                public BsonDocument AlsoAllowed() => Get();
                public object Unapproved() => Get();
            }
            """);

        Assert.NotEmpty(results);
        Assert.All(results, diagnostic => Assert.Contains("Unapproved", diagnostic.Location.SourceTree!
            .GetText().Lines.GetLineFromPosition(diagnostic.Location.SourceSpan.Start).ToString()));
    }

    [Theory]
    [InlineData("POLE014", "")]
    [InlineData("POLE014", "  ")]
    [InlineData("*", "Blanket suppression.")]
    [InlineData("", "Missing rule.")]
    public async Task Invalid_exceptions_are_errors_even_without_a_BSON_use(string rule, string reason)
    {
        Assert.NotEmpty(await Analyze($$"""
            [Pole.Architecture.ViolateArchitecture("{{rule}}", "{{reason}}")]
            public class Subject { }
            """));
    }

    [Fact]
    public async Task A_different_rule_does_not_suppress_raw_BSON()
    {
        Assert.NotEmpty(await Analyze("""
            [Pole.Architecture.ViolateArchitecture("POLE013", "A different deliberate exception.")]
            public class Subject { public MongoDB.Bson.BsonValue? Value; }
            """));
    }

    [Fact]
    public void Attribute_and_analyzer_agree_on_the_rule_id() =>
        Assert.Equal(ArchitectureRules.RawBson, RawBsonAnalyzer.DiagnosticId);

    [Fact]
    public async Task Named_constructor_arguments_keep_their_semantic_parameter_order()
    {
        Assert.Empty(await Analyze("""
            [Pole.Architecture.ViolateArchitecture(reason: "Specific driver boundary.", rule: "POLE014")]
            public class Subject { public MongoDB.Bson.BsonDocument Get() => BsonLibrary.Raw.Make(); }
            """));
    }

    [Fact]
    public async Task Compiler_suppression_cannot_replace_the_required_attribute()
    {
        Assert.NotEmpty(await Analyze("""
            #pragma warning disable POLE014
            public class Subject { public MongoDB.Bson.BsonDocument? Value; }
            """, suppress: true));
    }

    private static async Task<Diagnostic[]> Analyze(string source, string role = "Production",
        bool test = false, string path = "Feature.Application/Subject.cs", bool suppress = false)
    {
        var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview), path);
        var compilation = CSharpCompilation.Create("RawBsonSubject", [tree], References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable));
        if (suppress)
            compilation = compilation.WithOptions(compilation.Options.WithSpecificDiagnosticOptions(
                new Dictionary<string, ReportDiagnostic>
                { [RawBsonAnalyzer.DiagnosticId] = ReportDiagnostic.Suppress }));
        Assert.Empty(compilation.GetDiagnostics().Where(item => item.Severity == DiagnosticSeverity.Error));
        var options = new AnalyzerOptions([], new ProjectOptions(role, test));
        return (await compilation.WithAnalyzers([new RawBsonAnalyzer()], options)
            .GetAnalyzerDiagnosticsAsync()).ToArray();
    }

    private static MetadataReference BsonReference()
    {
        var source = """
            namespace MongoDB.Bson
            {
                public class BsonValue
                {
                    public static implicit operator BsonValue(int value) => new();
                }
                public class BsonDocument : BsonValue { }
                public class BsonArray : BsonValue { }
            }
            namespace BsonLibrary
            {
                public delegate void RawCallback(MongoDB.Bson.BsonDocument document);
                public static class Raw
                {
                    public static MongoDB.Bson.BsonDocument Make() => new();
                    public static MongoDB.Bson.BsonDocument? Maybe() => null;
                    public static void AcceptValue(MongoDB.Bson.BsonValue value) { }
                    public static void Visit(RawCallback callback) { }
                    public static bool TryValue(out MongoDB.Bson.BsonDocument document) { document = new(); return true; }
                    public static System.Collections.Generic.IEnumerable<MongoDB.Bson.BsonValue> Values => [];
                    public static System.Threading.Tasks.Task<MongoDB.Bson.BsonDocument> MakeTask() => null!;
                }
            }
            """;
        var compilation = CSharpCompilation.Create("RawBsonLibrary", [CSharpSyntaxTree.ParseText(source)],
            FrameworkReferences(), new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        using var stream = new MemoryStream();
        var result = compilation.Emit(stream);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        return MetadataReference.CreateFromImage(stream.ToArray());
    }

    private static IEnumerable<MetadataReference> FrameworkReferences() =>
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
        .Select(path => MetadataReference.CreateFromFile(path));

    private sealed class ProjectOptions(string role, bool test) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new Values(role, test);
        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => GlobalOptions;
        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => GlobalOptions;
    }

    private sealed class Values(string role, bool test) : AnalyzerConfigOptions
    {
        private readonly ImmutableDictionary<string, string> properties =
            new Dictionary<string, string>
            {
                ["build_property.PoleArchitectureRole"] = role,
                ["build_property.IsTestProject"] = test.ToString()
            }.ToImmutableDictionary();

        public override bool TryGetValue(string key, out string value) => properties.TryGetValue(key, out value!);
    }
}
